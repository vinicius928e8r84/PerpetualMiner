'use strict';

// A conferência de tamanho do gancho pre-commit (scripts/ganchos/limite-de-tokens.js): o limite, o que
// fica de fora (trava de pacotes, gerado, binário, de terceiros), a linha de base que só desce, o que
// é lido do índice e não da cópia de trabalho, e o texto do erro. A parte pura roda com tamanhos
// escritos à mão; a parte do git, num repositório de mentira criado e apagado aqui.

const assert = require('assert');
const { execFileSync, spawnSync } = require('child_process');
const fs = require('fs');
const os = require('os');
const path = require('path');
const {
  LIMITE_DE_BYTES, afrouxamentos, atualizarLinhaDeBase, avaliar, lerConfiguracao, limitarPeloHead, mensagemDeErro, tokensDe,
} = require('./limite-de-tokens.js');

const CLI = path.join(__dirname, 'limite-de-tokens.js');
const config = lerConfiguracao();
const arquivo = (caminho, tamanho, inicio) => ({ caminho, tamanho, inicio: inicio || (() => Buffer.alloc(tamanho, 'a')) });
const estadoDe = (caminho, tamanho, base, inicio) => avaliar(arquivo(caminho, tamanho, inicio), config, base || {}).estado;

// O limite: 5.000 tokens a 4 bytes por token. Passa até 20.000 bytes, falha com 20.001.
assert.strictEqual(LIMITE_DE_BYTES, 20000);
assert.strictEqual(tokensDe(20000), 5000);
assert.strictEqual(tokensDe(20001), 5001);
assert.strictEqual(estadoDe('lib/a.js', 20000), 'ok');
assert.strictEqual(estadoDe('lib/a.js', 20001), 'excede');
assert.strictEqual(estadoDe('lib/a.js', 0), 'ok');

// Trava de pacotes, saída gerada e código de terceiros não passam pelo limite.
for (const caminho of ['package-lock.json', 'e2e/package-lock.json', 'pnpm-lock.yaml', 'yarn.lock', 'poetry.lock',
  'uv.lock', 'Cargo.lock', 'sub/Gemfile.lock', 'dist/app.js', 'build/x.js', 'a/dist/x.js', 'coverage/lcov.info',
  'public/app.min.js', 'public/app.min.css', 'app.js.map', 'docs/design/voz/catalogo-textos.json', 'docs/design/voz/catalogo.html',
  'node_modules/x/index.js', 'vendor/x.js', 'third_party/y/z.js']) {
  assert.strictEqual(estadoDe(caminho, 90000), 'ignorado', caminho);
}
// O padrão por nome só vale para o nome inteiro, e dist/ só para uma pasta: não esconde um arquivo comum.
assert.strictEqual(estadoDe('lib/distribuir.js', 90000), 'excede');
assert.strictEqual(estadoDe('lib/lockfile.js', 90000), 'excede');

// Cabeçalho de arquivo gerado: só as marcas das ferramentas de geração, em maiúsculas/minúsculas exatas e
// nas primeiras linhas; um comentário qualquer que cite "auto-generated" não abre a porta.
const comCabecalho = linhas => () => Buffer.from(`${linhas}\n${'x'.repeat(30000)}`);
assert.strictEqual(estadoDe('a.js', 30000, {}, comCabecalho('// @generated by tool')), 'ignorado');
assert.strictEqual(estadoDe('a.go', 30000, {}, comCabecalho('// Code generated by x. DO NOT EDIT.')), 'ignorado');
assert.strictEqual(estadoDe('a.py', 30000, {}, comCabecalho('#!/usr/bin/env python\n# DO NOT EDIT - gerado')), 'ignorado');
assert.strictEqual(estadoDe('a.md', 30000, {}, comCabecalho('# Notas gerais\nGerado a mão por mim')), 'excede');
assert.strictEqual(estadoDe('a.js', 30000, {}, comCabecalho('// auto-generated')), 'excede');
assert.strictEqual(estadoDe('a.js', 30000, {}, comCabecalho('// this file is automatically generated')), 'excede');
assert.strictEqual(estadoDe('a.js', 30000, {}, comCabecalho('// do not edit')), 'excede');
const marcaLonge = () => Buffer.from(`${'linha\n'.repeat(40)}// @generated\n${'x'.repeat(30000)}`);
assert.strictEqual(estadoDe('b.js', 30000, {}, marcaLonge), 'excede');
// O conteúdo só é lido acima do limite: abaixo dele o arquivo nem é aberto.
let leu = false;
estadoDe('c.js', 100, {}, () => { leu = true; return Buffer.alloc(0); });
assert.strictEqual(leu, false);

// Binário: pela extensão ou por um byte nulo no começo (a regra do git).
assert.strictEqual(estadoDe('e2e/snap/tela-linux.png', 350000), 'ignorado');
assert.strictEqual(estadoDe('veio/fontes/x.woff2', 50000), 'ignorado');
assert.strictEqual(estadoDe('conexao/perpetualminer.ankiaddon', 74000), 'ignorado');
assert.strictEqual(estadoDe('dados.bin', 30000, {}, () => Buffer.from([1, 2, 0, 3, 4])), 'ignorado');

// A linha de base só desce: crescer além dela falha, ficar igual ou encolher passa.
const base = { 'painel.js': 78000 };
assert.strictEqual(estadoDe('painel.js', 78000, base), 'linha-de-base');
assert.strictEqual(estadoDe('painel.js', 70000, base), 'linha-de-base');
assert.strictEqual(estadoDe('painel.js', 15000, base), 'ok');
const cresceu = avaliar(arquivo('painel.js', 78001), config, base);
assert.strictEqual(cresceu.estado, 'cresceu');
assert.strictEqual(cresceu.naBase, 78000);
// Um arquivo novo acima do limite não é salvo pela linha de base dos outros.
assert.strictEqual(estadoDe('lib/novo.js', 20001, base), 'excede');
// Sem linha de base (modo estrito) tudo acima do limite falha.
assert.strictEqual(estadoDe('painel.js', 78000, {}), 'excede');

// A atualização da linha de base nunca sobe nem acrescenta; tira o que voltou ao limite ou sumiu.
assert.deepStrictEqual(
  atualizarLinhaDeBase({ a: 50000, b: 40000, c: 30000, d: 25000, e: 22000 }, { a: 45000, b: 41000, c: 19000, e: 22000, f: 99000 }),
  { a: 45000, b: 40000, e: 22000 },
);

// O teto de quem está na base é o menor entre a base e o tamanho no HEAD, e só vale se o HEAD já passava do limite.
assert.deepStrictEqual(
  limitarPeloHead({ a: 50000, b: 40000, c: 30000, d: 30000 }, { a: 45000, b: 60000, c: 10000 }),
  { a: 45000, b: 40000 },
);
// Uma base preparada não pode ter entrada que a do HEAD não tem, nem maior; sem base no HEAD, vale o tamanho do HEAD.
assert.deepStrictEqual(afrouxamentos({ a: 50000, b: 40000 }, { a: 50000, b: 40000 }, {}), []);
assert.deepStrictEqual(afrouxamentos({ a: 40000 }, { a: 50000, b: 40000 }, {}), []);
assert.deepStrictEqual(afrouxamentos({ a: 50001 }, { a: 50000 }, {}), [{ caminho: 'a', valor: 50001, permitido: 50000 }]);
assert.deepStrictEqual(afrouxamentos({ n: 30000 }, { a: 50000 }, { n: 30000 }), [{ caminho: 'n', valor: 30000, permitido: null }]);
assert.deepStrictEqual(afrouxamentos({ n: 30000 }, null, { n: 30000 }), []);
assert.deepStrictEqual(afrouxamentos({ n: 30000 }, null, { n: 25000 }), [{ caminho: 'n', valor: 30000, permitido: 25000 }]);
assert.deepStrictEqual(afrouxamentos({ n: 30000 }, null, {}), [{ caminho: 'n', valor: 30000, permitido: null }]);
assert.deepStrictEqual(afrouxamentos({ n: 30000 }, null, { n: 15000 }), [{ caminho: 'n', valor: 30000, permitido: null }]);

// A mensagem: caminho, bytes, tokens, limite e o passo a passo do tipo do arquivo.
const aviso = (caminho, tamanho, naBase) => mensagemDeErro(avaliar(arquivo(caminho, tamanho), config, naBase || {}), config);
const m1 = aviso('docs/guia grande.md', 31204);
for (const parte of ['docs/guia grande.md', '31204 bytes', '7801 tokens', '20000 bytes', '5000 tokens', 'índice', 'seção', 'git add']) {
  assert.ok(m1.includes(parte), `${parte}\n${m1}`);
}
assert.ok(aviso('e2e/tests/popup.spec.js', 30000).includes('cenário'));
assert.ok(aviso('complemento/test_servidor.py', 30000).includes('cenário'));
assert.ok(aviso('engine/start.py', 30000).includes('módulo'));
assert.ok(aviso('painel.js', 30000).includes('módulo'));
assert.ok(aviso('painel.css', 30000).includes('CSS'));
assert.ok(aviso('docs/x/prototipo.html', 30000).includes('HTML'));
assert.ok(aviso('x/dados.json', 30000).includes('coleção'));
assert.ok(aviso('x/qualquer.coisa', 30000).includes('responsabilidade'));
assert.ok(aviso('lib/a.js', 30000).includes('"ignorar"'));
const m2 = aviso('painel.js', 78001, { 'painel.js': 78000 });
assert.ok(m2.includes('linha de base') && m2.includes('78000') && m2.includes('78001'), m2);
assert.ok(m2.includes('--atualizar-linha-de-base'));

// O git de verdade: um repositório de mentira com o gancho rodando como linha de comando.
const raizDeMentira = fs.mkdtempSync(path.join(os.tmpdir(), 'limite-de-tokens-'));
// Sem ganchos no repositório de mentira: o core.hooksPath de quem roda o teste não pode entrar nos commits daqui.
const git = (...args) => execFileSync('git', ['-c', 'core.hooksPath=/dev/null', ...args], { cwd: raizDeMentira, encoding: 'utf8' });
const escrever = (caminho, conteudo) => {
  fs.mkdirSync(path.dirname(path.join(raizDeMentira, caminho)), { recursive: true });
  fs.writeFileSync(path.join(raizDeMentira, caminho), conteudo);
};
const rodar = (...args) => spawnSync('node', [CLI, ...args], { cwd: raizDeMentira, encoding: 'utf8' });
// Passou de verdade: status 0 e nenhum "aviso:" (uma pane do gancho também sai com 0, mas avisa).
const passa = (...args) => {
  const r = rodar(...args);
  assert.strictEqual(r.status, 0, r.stdout + r.stderr);
  assert.ok(!r.stderr.includes('aviso:'), r.stderr);
  return r;
};
const barra = (...args) => {
  const r = rodar(...args);
  assert.strictEqual(r.status, 1, r.stdout + r.stderr);
  assert.ok(!r.stderr.includes('aviso:'), r.stderr);
  return r;
};
const LINHA_DE_BASE = 'scripts/ganchos/linha-de-base-de-tamanho.json';
const gravarBase = arquivos => escrever(LINHA_DE_BASE, `${JSON.stringify({ descricao: 'x', arquivos }, null, 2)}\n`);
const baseGravada = () => JSON.parse(fs.readFileSync(path.join(raizDeMentira, LINHA_DE_BASE), 'utf8')).arquivos;
const commit = mensagem => git('commit', '-q', '-m', mensagem);
try {
  git('init', '-q');
  git('config', 'user.email', 't@t.t');
  git('config', 'user.name', 't');
  git('config', 'core.autocrlf', 'false');

  // Nada preparado (e nenhum commit ainda): passa.
  passa();

  // No limite exato passa; um byte a mais falha, com o nome (com espaço) e os números.
  escrever('lib/no limite.js', 'a'.repeat(20000));
  escrever('lib/acima do limite.js', 'a'.repeat(20001));
  git('add', '-A');
  let r = barra();
  assert.ok(r.stderr.includes('lib/acima do limite.js') && r.stderr.includes('20001 bytes'), r.stderr);
  assert.ok(!r.stderr.includes('lib/no limite.js'), r.stderr);

  // O índice manda, não a cópia de trabalho: o arquivo grande preparado e depois enxugado ainda falha...
  escrever('lib/acima do limite.js', 'a'.repeat(100));
  barra();
  // ...e o pequeno preparado e depois engordado passa.
  git('reset', '-q', '--', 'lib/acima do limite.js');
  fs.unlinkSync(path.join(raizDeMentira, 'lib/acima do limite.js'));
  escrever('lib/pequeno.js', 'a'.repeat(100));
  git('add', 'lib/pequeno.js');
  escrever('lib/pequeno.js', 'a'.repeat(50000));
  passa();

  // Trava de pacotes e binário grandes passam; o que está só na cópia de trabalho nem é visto.
  escrever('package-lock.json', 'x'.repeat(90000));
  fs.writeFileSync(path.join(raizDeMentira, 'tela.bin'), Buffer.concat([Buffer.from([0, 1, 2]), Buffer.alloc(90000, 7)]));
  escrever('solto.js', 'a'.repeat(90000));
  git('add', 'package-lock.json', 'tela.bin');
  passa();

  // Arquivo apagado não é lido.
  commit('base');
  git('rm', '-q', 'lib/no limite.js');
  passa();
  commit('sem o arquivo');

  // Sem linha de base (modo estrito), o arquivo grande novo falha.
  escrever('grande.js', 'a'.repeat(30000));
  git('add', 'grande.js');
  barra();

  // A linha de base nasce só com o que o HEAD já tinha acima do limite: o grande.js ainda não está no HEAD...
  gravarBase({ 'grande.js': 30000 });
  git('add', LINHA_DE_BASE);
  r = barra();
  assert.ok(r.stderr.includes('afrouxada') && r.stderr.includes('grande.js'), r.stderr);
  // ...com ele no HEAD (entrou sem o gancho), a base que o lista passa.
  git('reset', '-q', LINHA_DE_BASE);
  commit('grande.js sem o gancho');
  git('add', LINHA_DE_BASE);
  passa();
  commit('linha de base');

  // Com a base no HEAD: crescer falha, ficar igual ou encolher passa.
  escrever('grande.js', 'a'.repeat(30001));
  git('add', 'grande.js');
  r = barra();
  assert.ok(r.stderr.includes('30000') && r.stderr.includes('30001'), r.stderr);
  escrever('grande.js', 'a'.repeat(25000));
  git('add', 'grande.js');
  passa();

  // (b) A base editada só no disco, sem git add, não vale: o índice e o HEAD é que contam.
  escrever('grande.js', 'a'.repeat(40000));
  git('add', 'grande.js');
  gravarBase({ 'grande.js': 40000 });
  barra();
  // (a) Preparar a base com o tamanho maior, ou com um arquivo novo, também é barrado.
  git('add', LINHA_DE_BASE);
  r = barra();
  assert.ok(r.stderr.includes('afrouxada') && r.stderr.includes('grande.js') && r.stderr.includes('30000'), r.stderr);
  escrever('novo/enorme.js', 'a'.repeat(30000));
  gravarBase({ 'grande.js': 30000, 'novo/enorme.js': 30000 });
  git('add', LINHA_DE_BASE, 'novo/enorme.js');
  escrever('grande.js', 'a'.repeat(30000));
  git('add', 'grande.js');
  r = barra();
  assert.ok(r.stderr.includes('novo/enorme.js') && r.stderr.includes('afrouxada'), r.stderr);
  // O que desfaz tudo isso volta a passar.
  git('rm', '-q', '--cached', 'novo/enorme.js');
  fs.rmSync(path.join(raizDeMentira, 'novo'), { recursive: true });
  git('checkout', 'HEAD', '--', LINHA_DE_BASE, 'grande.js');
  passa();

  // (c) Gerar a base do zero é recusado quando já existe uma; ela só desce, por --atualizar-linha-de-base.
  escrever('b/um.js', 'a'.repeat(21000));
  git('add', 'b/um.js');
  r = barra('--gerar-linha-de-base');
  assert.ok(r.stderr.includes('--atualizar-linha-de-base'), r.stderr);
  assert.deepStrictEqual(baseGravada(), { 'grande.js': 30000 });
  git('reset', '-q', 'b/um.js');
  fs.rmSync(path.join(raizDeMentira, 'b'), { recursive: true });

  // C2: encolheu e foi commitado; a base antiga (30000) não deixa o arquivo voltar a crescer além do HEAD.
  escrever('grande.js', 'a'.repeat(25000));
  git('add', 'grande.js');
  commit('grande.js encolheu');
  escrever('grande.js', 'a'.repeat(29000));
  git('add', 'grande.js');
  r = barra();
  assert.ok(r.stderr.includes('25000') && r.stderr.includes('29000'), r.stderr);
  escrever('grande.js', 'a'.repeat(15000));
  git('add', 'grande.js');
  commit('grande.js abaixo do limite');
  escrever('grande.js', 'a'.repeat(21000));
  git('add', 'grande.js');
  barra();
  escrever('grande.js', 'a'.repeat(25000));
  git('add', 'grande.js');
  git('reset', '-q', '--hard', 'HEAD');

  // A atualização da linha de base lê o índice, baixa o que encolheu e remove o que voltou ao limite ou foi ignorado.
  escrever('grande.js', 'a'.repeat(25000));
  git('add', 'grande.js');
  commit('grande.js 25000');
  passa('--atualizar-linha-de-base');
  assert.deepStrictEqual(baseGravada(), { 'grande.js': 25000 });
  git('add', LINHA_DE_BASE);
  passa();
  commit('base 25000');
  escrever('grande.js', 'a'.repeat(500));
  git('add', 'grande.js');
  passa('--atualizar-linha-de-base');
  assert.deepStrictEqual(baseGravada(), {});
  git('add', LINHA_DE_BASE);
  passa();
  commit('base vazia');

  // Modo estrito: sem o arquivo da linha de base, tudo acima do limite falha; e gerar a base do zero lista
  // só o que o índice tem acima do limite (menos os ignorados), e só vale se o HEAD já tinha o arquivo.
  git('rm', '-q', LINHA_DE_BASE);
  passa();
  commit('modo estrito');
  escrever('b/um.js', 'a'.repeat(21000));
  escrever('b/dois.md', 'a'.repeat(40000));
  escrever('b/imagem.png', 'a'.repeat(40000));
  git('add', 'b');
  commit('dois grandes sem o gancho');
  passa('--gerar-linha-de-base');
  assert.deepStrictEqual(baseGravada(), { 'b/dois.md': 40000, 'b/um.js': 21000 });
  git('add', LINHA_DE_BASE);
  passa();
  escrever('b/tres.md', 'a'.repeat(30000));
  git('add', 'b/tres.md');
  barra();
  git('reset', '-q', '--', LINHA_DE_BASE);
  passa('--gerar-linha-de-base');
  git('add', LINHA_DE_BASE);
  r = barra();
  assert.ok(r.stderr.includes('b/tres.md') && r.stderr.includes('afrouxada'), r.stderr);
} finally {
  fs.rmSync(raizDeMentira, { recursive: true, force: true });
}

// O instalador (instalar.mjs): liga o core.hooksPath, mesmo com a configuração de linha de comando de quem o roda
// (o escopo `command` não conta), não troca uma pasta de ganchos já escolhida, avisa dos ganchos que desliga e
// não faz nada no CI.
const raizDoInstalador = fs.mkdtempSync(path.join(os.tmpdir(), 'limite-de-tokens-instalar-'));
try {
  const gi = (...args) => execFileSync('git', args, { cwd: raizDoInstalador, encoding: 'utf8', env: { ...process.env, GIT_CONFIG_PARAMETERS: '' } });
  gi('init', '-q', '--template='); // sem os ganchos do modelo do git de quem roda o teste
  fs.mkdirSync(path.join(raizDoInstalador, '.git/hooks'), { recursive: true });
  fs.mkdirSync(path.join(raizDoInstalador, 'scripts/ganchos'), { recursive: true });
  fs.copyFileSync(path.join(__dirname, 'instalar.mjs'), path.join(raizDoInstalador, 'scripts/ganchos/instalar.mjs'));
  const instalar = env => spawnSync('node', ['scripts/ganchos/instalar.mjs'], {
    cwd: raizDoInstalador, encoding: 'utf8', env: { ...process.env, GIT_CONFIG_PARAMETERS: '', CI: '', ...env },
  });
  const hooksPath = () => spawnSync('git', ['config', '--local', '--get', 'core.hooksPath'], { cwd: raizDoInstalador, encoding: 'utf8' }).stdout.trim();

  // No CI não liga.
  instalar({ CI: 'true' });
  assert.strictEqual(hooksPath(), '');
  // Com um core.hooksPath de linha de comando no ambiente (como nas worktrees da frota), liga do mesmo jeito.
  let r = instalar({ GIT_CONFIG_PARAMETERS: "'core.hookspath=/outro/lugar'" });
  assert.strictEqual(hooksPath(), 'scripts/ganchos', r.stdout + r.stderr);
  // Já ligado: repete sem mudar.
  instalar();
  assert.strictEqual(hooksPath(), 'scripts/ganchos');
  // Outra pasta escolhida no clone: não troca.
  gi('config', 'core.hooksPath', 'minha/pasta');
  r = instalar();
  assert.strictEqual(hooksPath(), 'minha/pasta');
  assert.ok(r.stdout.includes('minha/pasta'), r.stdout);
  // Ganchos em .git/hooks deixam de rodar: o instalador diz quais.
  gi('config', '--unset', 'core.hooksPath');
  fs.writeFileSync(path.join(raizDoInstalador, '.git/hooks/pre-push'), '#!/bin/sh\n');
  fs.writeFileSync(path.join(raizDoInstalador, '.git/hooks/commit-msg.sample'), '#!/bin/sh\n');
  r = instalar();
  assert.strictEqual(hooksPath(), 'scripts/ganchos');
  assert.ok(r.stdout.includes('pre-push') && !r.stdout.includes('commit-msg'), r.stdout);
} finally {
  fs.rmSync(raizDoInstalador, { recursive: true, force: true });
}

// Rápido: o gancho olha só o que está preparado (um commit de um arquivo pequeno leva bem menos de 1 s).
const raizRapida = fs.mkdtempSync(path.join(os.tmpdir(), 'limite-de-tokens-rapido-'));
try {
  execFileSync('git', ['init', '-q'], { cwd: raizRapida });
  fs.writeFileSync(path.join(raizRapida, 'a.js'), 'x');
  execFileSync('git', ['add', 'a.js'], { cwd: raizRapida });
  const inicio = Date.now();
  const r = spawnSync('node', [CLI], { cwd: raizRapida, encoding: 'utf8' });
  assert.strictEqual(r.status, 0, r.stderr);
  assert.ok(Date.now() - inicio < 3000, `levou ${Date.now() - inicio} ms`);
} finally {
  fs.rmSync(raizRapida, { recursive: true, force: true });
}

