const LINHA_DE_BASE = 'scripts/ganchos/linha-de-base-de-tamanho.json';

function criarRepositorioDeMentira() {
  const raiz = fs.mkdtempSync(path.join(os.tmpdir(), 'limite-de-tokens-'));
  const gitSemGanchos = (...args) => execFileSync('git', ['-c', 'core.hooksPath=/dev/null', ...args], { cwd: raiz, encoding: 'utf8' });
  const escrever = (caminho, conteudo) => {
    fs.mkdirSync(path.dirname(path.join(raiz, caminho)), { recursive: true });
    fs.writeFileSync(path.join(raiz, caminho), conteudo);
  };
  const rodar = (...args) => spawnSync('node', [CLI, ...args], { cwd: raiz, encoding: 'utf8' });
  const sair = (status, ...args) => {
    const r = rodar(...args);
    assert.strictEqual(r.status, status, r.stdout + r.stderr);
    assert.ok(!r.stderr.includes('aviso:'), r.stderr);
    return r;
  };
  return {
    raiz,
    git: gitSemGanchos,
    escrever,
    passa: (...args) => sair(0, ...args),
    barra: (...args) => sair(1, ...args),
    apagar: caminho => fs.rmSync(path.join(raiz, caminho), { recursive: true }),
    gravarBase: arquivos => escrever(LINHA_DE_BASE, `${JSON.stringify({ descricao: 'x', arquivos }, null, 2)}\n`),
    baseGravada: () => JSON.parse(fs.readFileSync(path.join(raiz, LINHA_DE_BASE), 'utf8')).arquivos,
    commit: mensagem => gitSemGanchos('commit', '-q', '-m', mensagem),
  };
}

function provarLimiteNoIndice({ git, escrever, passa, barra, apagar }) {
  passa();

  escrever('lib/no limite.js', 'a'.repeat(20000));
  escrever('lib/acima do limite.js', 'a'.repeat(20001));
  git('add', '-A');
  const r = barra();
  assert.ok(r.stderr.includes('lib/acima do limite.js') && r.stderr.includes('20001 bytes'), r.stderr);
  assert.ok(!r.stderr.includes('lib/no limite.js'), r.stderr);

  escrever('lib/acima do limite.js', 'a'.repeat(100));
  barra();
  git('reset', '-q', '--', 'lib/acima do limite.js');
  apagar('lib/acima do limite.js');
  escrever('lib/pequeno.js', 'a'.repeat(100));
  git('add', 'lib/pequeno.js');
  escrever('lib/pequeno.js', 'a'.repeat(50000));
  passa();
}

